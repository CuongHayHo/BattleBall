def load(name):
    return json.load(open(os.path.join(SEED, name), encoding="utf-8"))


def q(v):
    """SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v) if isinstance(v, float) else str(v)
    if isinstance(v, (dict, list)):
        v = json.dumps(v, ensure_ascii=False, separators=(",", ":"))
    s = str(v).replace("\\", "\\\\").replace("'", "''")
    return "'" + s + "'"


def insert(table, cols, rows, ignore_dups_on=None, chunk=100):
    out = []
    col_sql = ", ".join("`%s`" % c for c in cols)
    for i in range(0, len(rows), chunk):
        part = rows[i:i + chunk]
        vals = ",\n  ".join("(" + ", ".join(q(x) for x in r) + ")" for r in part)
        sql = "INSERT INTO `%s` (%s) VALUES\n  %s" % (table, col_sql, vals)
        if ignore_dups_on:
            upd = ", ".join("`%s` = VALUES(`%s`)" % (c, c) for c in cols if c not in ignore_dups_on)
            sql += "\nON DUPLICATE KEY UPDATE " + upd
        out.append(sql + ";")
    return "\n".join(out)


