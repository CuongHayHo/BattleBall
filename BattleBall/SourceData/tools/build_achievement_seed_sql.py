"""Generates BattleBallServer/db/migrations/V007__achievements.sql: achievement tables + a PROPOSED seed that unlocks the
avatars (kind COMPONENT) that are not race starters, by reaching character levels (owner decision 2026-10-07: option B, achievements).

Avatars are read from V002 (skin_template rows with kind COMPONENT); the 9 starters of race_default_skin (412-420) are excluded.
Per race the remaining avatars are spread over levels 10..100 in steps of 5 (the VIP avatar last, at level 100).
Safe to re-run; overwrites V007 only.
"""
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIG = os.path.normpath(os.path.join(ROOT, "..", "..", "BattleBallServer", "db", "migrations"))
RACES = {"0": "EARTH", "1": "NAMEC", "2": "XAYDA"}
RACE_VI = {"EARTH": "Trái Đất", "NAMEC": "Namếc", "XAYDA": "Xayda"}

seed = open(os.path.join(MIG, "V002__static_data_seed.sql"), encoding="utf-8").read()
by_race = {}
for m in re.finditer(r"^\s*\((\d+), '([^']*)', (\d), '[^']*', 'Component', \d+, 'COMPONENT'", seed, re.M):
    cid, name, gender = int(m.group(1)), m.group(2), m.group(3)
    if 412 <= cid <= 420 or gender not in RACES:
        continue
    by_race.setdefault(RACES[gender], []).append((cid, name))

rows = []
aid = 1
for race in ("EARTH", "NAMEC", "XAYDA"):
    items = sorted(by_race.get(race, []), key=lambda x: (x[1] == "Avatar VIP", x[0]))
    n = len(items)
    for i, (cid, name) in enumerate(items):
        lvl = 100 if n == 1 else 10 + 5 * round((90 * i / (n - 1)) / 5)
        rows.append((aid, "Đạt cấp %d (%s)" % (lvl, RACE_VI[race]), race, lvl, cid))
        aid += 1

out = []
w = out.append
w("-- BattleBallServer: achievements (reward = an avatar skin or gems). GENERATED by BattleBall/SourceData/tools/build_achievement_seed_sql.py.")
w("-- Status: PROPOSED. Owner decision 2026-10-07: avatars outside the race starters are obtained through achievements (option B).")
w("-- The conditions below (reach a character level) are my proposal; the admin page edits thresholds, rewards and enabled flags.")
w("SET NAMES utf8mb4;")
w("SET FOREIGN_KEY_CHECKS = 0;")
w("")
w("CREATE TABLE IF NOT EXISTS achievement_template (")
w("  achievement_id   INT UNSIGNED NOT NULL,")
w("  name_vi          VARCHAR(120) NOT NULL,")
w("  race             ENUM('EARTH','NAMEC','XAYDA','ANY') NOT NULL DEFAULT 'ANY',  -- which character can earn it")
w("  condition_type   ENUM('LEVEL_REACH','WINS_TOTAL','FIRST_CLEAR_BOSS') NOT NULL,")
w("  threshold        INT UNSIGNED NOT NULL,                -- level / number of wins / boss id")
w("  reward_costume_id INT UNSIGNED NULL,                   -- skin granted (owned_skin.source = 'REWARD')")
w("  reward_gems      INT UNSIGNED NULL,")
w("  enabled          TINYINT(1)   NOT NULL DEFAULT 1,")
w("  updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,")
w("  updated_by       VARCHAR(64)  NULL,")
w("  PRIMARY KEY (achievement_id),")
w("  KEY idx_ach_cond (condition_type, enabled),")
w("  CONSTRAINT fk_ach_skin FOREIGN KEY (reward_costume_id) REFERENCES skin_template (costume_id)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
w("CREATE TABLE IF NOT EXISTS character_achievement (")
w("  character_id   BIGINT UNSIGNED NOT NULL,")
w("  achievement_id INT UNSIGNED    NOT NULL,")
w("  completed_at   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,")
w("  PRIMARY KEY (character_id, achievement_id),")
w("  CONSTRAINT fk_cach_char FOREIGN KEY (character_id)   REFERENCES game_character (character_id) ON DELETE CASCADE,")
w("  CONSTRAINT fk_cach_ach  FOREIGN KEY (achievement_id) REFERENCES achievement_template (achievement_id)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
w("SET FOREIGN_KEY_CHECKS = 1;")
w("")
w("INSERT INTO static_data_version (domain, version, updated_by) VALUES ('ACHIEVEMENT', 1, 'seed');")
w("")
w("INSERT INTO achievement_template (achievement_id, name_vi, race, condition_type, threshold, reward_costume_id, updated_by) VALUES")
w(",\n".join("  (%d, '%s', '%s', 'LEVEL_REACH', %d, %d, 'seed')" % r for r in rows) + ";")
w("")
with open(os.path.join(MIG, "V007__achievements.sql"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("achievements:", len(rows), {k: len(v) for k, v in by_race.items()})
