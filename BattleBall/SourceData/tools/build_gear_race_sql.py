#!/usr/bin/env python3
"""Generate BattleBallServer/db/migrations/V038__gear_per_planet.sql: every set of gear exists once for each planet (owner remark 2026-10-10:
"mỗi hành tinh có đồ thần linh, hủy diệt, thiên sứ khác nhau").

In Nro the pieces of a set are made per planet (item_template.gender 0 Trái Đất, 1 Namếc, 2 Xayda; the rings of the first two sets are shared) and show different pictures. Here:
  * item_template gets a `race` column and the unique key becomes (slot, tier, race);
  * the 15 pieces that exist (ids 1 to 15, V037) are the Trái Đất pieces; Namếc gets ids 16 to 30 and Xayda ids 31 to 45, in the same order (set by set: Áo, Quần, Găng, Giày, Nhẫn);
  * the stats, level and number of fragments of a piece do not depend on the planet; the picture is the Nro one of that planet; the name is "<piece> <set> <planet>";
  * the fragments stay one kind per piece of a set (101 to 115): the fragments of an Áo Hủy Diệt make the Áo Hủy Diệt of any planet, as the "Mảnh áo" of Nro do for any gender.
Wearing is not tied to the planet (the three characters share one inventory and any of them may wear any piece, as V026 decided): that is OPEN (docs 15.18).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "BattleBallServer", "db", "migrations", "V038__gear_per_planet.sql"))
ITEMS = os.path.normpath(os.path.join(HERE, "..", "tables", "json", "item_template.json"))

SLOTS = [("ARMOR", "Áo", "armor", "FLAT_ARMOR"), ("PANTS", "Quần", "pants", "FLAT_HP"), ("GLOVES", "Găng", "gloves", "FLAT_ATK"),
         ("BOOTS", "Giày", "boots", "FLAT_KI"), ("RING", "Nhẫn", "ring", "CRIT_DMG_PCT")]
SETS = [("Thần Linh", "god", 1, 1.0, 1), ("Hủy Diệt", "destroyer", 2, 1.5, 30), ("Thiên Sứ", "angel", 3, 2.0, 60)]
BASE = {"ARMOR": 2500.0, "PANTS": 200000.0, "GLOVES": 20000.0, "BOOTS": 200000.0, "RING": 25.0}
RACES = [("EARTH", "Trái Đất", "earth"), ("NAMEC", "Namếc", "namec"), ("XAYDA", "Xayda", "xayda")]
# Nro item ids of the pieces: [set][slot] -> (Trái Đất, Namếc, Xayda); the rings of the first two sets are one item for every planet
NRO = [
    {"ARMOR": (555, 557, 559), "PANTS": (556, 558, 560), "GLOVES": (562, 564, 566), "BOOTS": (563, 565, 567), "RING": (561, 561, 561)},
    {"ARMOR": (650, 652, 654), "PANTS": (651, 653, 655), "GLOVES": (657, 659, 661), "BOOTS": (658, 660, 662), "RING": (656, 656, 656)},
    {"ARMOR": (1048, 1049, 1050), "PANTS": (1051, 1052, 1053), "GLOVES": (1054, 1055, 1056), "BOOTS": (1057, 1058, 1059), "RING": (1060, 1061, 1062)},
]


def fmt(v):
    return ("%.2f" % v)


def main():
    nro = {r["id"]: r for r in json.load(open(ITEMS, encoding="utf-8"))["rows"]}
    lines = []
    icons = set()
    for si, (set_name, set_key, tier, mult, level) in enumerate(SETS):
        for ri, (race, planet, race_key) in enumerate(RACES):
            for ki, (slot, piece, slot_key, stat) in enumerate(SLOTS):
                tid = ri * 15 + si * 5 + ki + 1
                icon = nro[NRO[si][slot][ri]]["icon_id"]
                icons.add(icon)
                lines.append((tid, slot, race, piece + " " + set_name + " " + planet, tier, stat, BASE[slot] * mult, level, icon, slot_key + "_" + set_key + "_" + race_key,
                              "Bộ %s (bậc %d) của %s: x%s chỉ số cơ bản của kế hoạch" % (set_name, tier, planet, ("%g" % mult).replace(".", ","))))
    out = ["-- BattleBallServer: every set of gear exists once for each planet (owner remark 2026-10-10: \"mỗi hành tinh có đồ thần linh, hủy diệt, thiên sứ khác nhau\",",
           "-- docs/architecture/BattleBallServer.md 15.18). Generated by BattleBall/SourceData/tools/build_gear_race_sql.py (do not edit by hand).",
           "-- item_template gets a race; the pieces of V037 (ids 1 to 15) are the Trái Đất ones, Namếc has ids 16 to 30 and Xayda 31 to 45 (set by set: Áo, Quần, Găng, Giày, Nhẫn).",
           "-- Stats, level and the 10 fragments of a piece do not depend on the planet; the fragments (101 to 115) are one kind per piece of a set and make that piece for any planet.",
           "-- The pictures are the Nro ones of each planet. Wearing is not tied to the planet (shared inventory, V026): OPEN.",
           "SET NAMES utf8mb4;", "",
           "ALTER TABLE item_template ADD COLUMN race ENUM('EARTH','NAMEC','XAYDA') NOT NULL DEFAULT 'EARTH' AFTER slot;",
           "ALTER TABLE item_template DROP INDEX uq_item_slot_tier, ADD UNIQUE KEY uq_item_slot_tier_race (slot, tier, race);", ""]
    for (tid, slot, race, name, tier, stat, value, level, icon, key, note) in lines:
        if tid <= 15:
            out.append("UPDATE item_template SET race = '%s', name_vi = '%s', icon_id = %d, note = '%s' WHERE template_id = %d;" % (race, name, icon, note, tid))
    out.append("")
    out.append("INSERT INTO item_template (template_id, item_key, slot, race, name_vi, tier, base_stat_key, base_value, pieces_needed, min_level, icon_id, enabled, note, updated_by) VALUES")
    rows = ["  (%d, '%s', '%s', '%s', '%s', %d, '%s', %s, 10, %d, %d, 1, '%s', 'V038')" % (tid, key, slot, race, name, tier, stat, fmt(value), level, icon, note)
            for (tid, slot, race, name, tier, stat, value, level, icon, key, note) in lines if tid > 15]
    out.append(",\n".join(rows) + ";")
    out.append("")
    out.append("UPDATE static_data_version SET version = version + 1, updated_by = 'V038' WHERE domain = 'BALANCE';")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT, "| pieces", len(lines), "| new", len([l for l in lines if l[0] > 15]))
    print("icons:", sorted(icons))


if __name__ == "__main__":
    main()
