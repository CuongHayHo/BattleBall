#!/usr/bin/env python3
"""Generate BattleBallServer/db/migrations/V034__restore_hidden_skins.sql: the 132 skins that were hidden and are sold again (restore_hidden_skins.py).

V002 is never regenerated (a migration that was applied must not change), so the restored skins come as their own migration: the rows of skin_template,
skin_stat and skin_nro_stat for every skin of skin_pricing.json that is not among the 221 of the round 2 export (the 221 that V002 inserted).
Re-run safe: the output only depends on the seed files.
"""
import csv
import json
import os

from build_static_seed_sql import insert

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = os.path.normpath(os.path.join(HERE, "..", "tables", "seed"))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "BattleBallServer", "db", "migrations", "V034__restore_hidden_skins.sql"))


def main():
    skin = json.load(open(os.path.join(SEED, "skin_pricing.json"), encoding="utf-8"))
    stat_keys = {s["key"] for s in json.load(open(os.path.join(SEED, "skin_stat_catalog.json"), encoding="utf-8"))["stats"]}
    with open(os.path.join(SEED, "skin_user_edit_round2.csv"), encoding="utf-8-sig", newline="") as f:
        in_v002 = {int(r["costumeId"]) for r in csv.DictReader(f) if r["kind"] != "HIDDEN"}
    new = [c for c in skin["costumes"] if c["costumeId"] not in in_v002]
    rows, srows, nrows = [], [], []
    for c in new:
        n = c["nro"]
        rows.append([c["costumeId"], c["name"], c["gender"], c["genderName"], c["bodyGroup"], c["iconId"], c["kind"],
                     c.get("rarity"), c.get("rarityStatus"), c.get("gemPrice"), c.get("fusionRace"),
                     0, 1, (n["description"] or "")[:250], 1 if n["soldInNroShop"] else 0, n["nroGemCost"],
                     1 if n["eventItem"] else 0, "V034"])
        for st in c.get("stats", []):
            assert st["type"] in stat_keys, st
            srows.append([c["costumeId"], st["type"], st["value"], "V034"])
        for st in c.get("nroStats", []):
            assert st["type"] in stat_keys, st
            nrows.append([c["costumeId"], st["type"], st["nroValue"]])
    head = ("-- BattleBallServer: the %d skins the owner had hidden come back as SHOP skins (owner decision 2026-10-10, docs/architecture/BattleBallServer.md 15.16).\n"
            "-- Only skins made of three parts (head, body, leg); the hidden avatars stay out. Rarity is the data-driven one (HEURISTIC), the price is the base price of the\n"
            "-- body group times the rarity factor, the stats are the default ATK_PCT, HP_PCT, KI_PCT of the rarity: the admin page changes any of them.\n"
            "-- Generated by BattleBall/SourceData/tools/build_restored_skins_sql.py from skin_pricing.json (do not edit by hand).\n"
            "SET NAMES utf8mb4;\n\n") % len(new)
    parts = [head,
             insert("skin_template", ["costume_id", "name", "gender_id", "gender_name", "body_group", "icon_id", "kind_key", "rarity_key", "rarity_status", "gem_price",
                                      "fusion_race", "ai_can_wear", "enabled", "nro_description", "nro_sold", "nro_gem_cost", "nro_event_item", "updated_by"], rows),
             insert("skin_stat", ["costume_id", "stat_key", "value", "updated_by"], srows)]
    if nrows:
        parts.append(insert("skin_nro_stat", ["costume_id", "stat_key", "nro_value"], nrows))
    parts.append("\nUPDATE static_data_version SET version = version + 1, updated_by = 'V034' WHERE domain = 'SKIN';\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts))
    print("wrote", OUT, "| skins %d, stats %d, nro stats %d" % (len(rows), len(srows), len(nrows)))


if __name__ == "__main__":
    main()
