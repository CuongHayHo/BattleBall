"""Generates BattleBallServer/db/migrations/V006__support_items_seed.sql from the NRO tables in SourceData/tables/json.

Source of every number: docs/database/BattleBall.md 10.21 (read from the Teamobi2026 source and nro1.sql) and 10.22 (owner approval).
Items taken: pets with a stat effect, 4 training armor levels, flag/wing/weapon items with HP/Ki/ATK stats, 2 skill books.
Safe to re-run; it overwrites V006 only.
"""
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON = os.path.join(ROOT, "tables", "json")
OUT = os.path.normpath(os.path.join(ROOT, "..", "..", "BattleBallServer", "db", "migrations", "V006__support_items_seed.sql"))


def load(name):
    with open(os.path.join(JSON, name + ".json"), encoding="utf-8") as f:
        return json.load(f)["rows"]


items = {r["id"]: r for r in load("item_template")}
shop = {s["id"]: s for s in load("item_shop")}
shop_opts = {}
for r in load("item_shop_option"):
    s = shop.get(r["item_shop_id"])
    if s:
        shop_opts.setdefault(s["temp_id"], {}).setdefault(s["id"], {})[r["option_id"]] = r["param"]


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


GEM_PRICE = 150          # GDD 6: permanent decoration item = 150 gems (PROPOSED for all shop items here)

# (item id, stat_key, value, duration_s); 1203 is a duplicate of 1202 (same name) and is skipped.
PETS = [
    (1107, "ARMOR_PCT", 5, 5), (1114, "CRIT_RATE_PCT", 5, 5), (1188, "CRIT_RATE_PCT", 5, 5),
    (1202, "CRIT_RATE_PCT", 3, 5), (1207, "CRIT_RATE_PCT", 3, 5), (1224, "ARMOR_PCT", 15, 10),
    (1225, "ARMOR_PCT", 15, 10), (1226, "ARMOR_PCT", 15, 10), (1435, "CRIT_RATE_PCT", 5, 5),
    (1497, "ARMOR_PCT", 10, 5),
]
# (item id, level, penalty/bonus pct)
TRAIN = [(529, 1, 10), (530, 2, 20), (531, 3, 30), (1716, 4, 40)]
BOOKS = [1044, 1278]
FLAG_OPTS = {50: "ATK_PCT", 77: "HP_PCT", 103: "KI_PCT", 5: "CRIT_DMG_PCT"}
# skill book pool: stat -> (min, max); the NRO roll is 1..10 (or 1..5); capped by stat_type.suggested_max.
POOL = [("HP_PCT", 1, 10), ("KI_PCT", 1, 10), ("ATK_PCT", 1, 10), ("DODGE_PCT", 1, 5), ("ARMOR_PCT", 1, 10),
        ("CRIT_RATE_PCT", 1, 3), ("HP_REGEN_PCT", 0.1, 1), ("KI_REGEN_PCT", 0.2, 2), ("CRIT_DMG_PCT", 1, 10),
        ("ULT_RANGE_PCT", 1, 10), ("ULT_DMG_PCT", 1, 10)]

flags = []
for tid, variants in shop_opts.items():
    it = items.get(tid)
    if not it or it["TYPE"] != 11:
        continue
    best = None
    for opts in variants.values():
        stats = {FLAG_OPTS[o]: p for o, p in opts.items() if o in FLAG_OPTS and p > 0}
        if stats and (best is None or stats.get("ATK_PCT", 0) > best.get("ATK_PCT", 0)):
            best = stats
    if best:
        flags.append((tid, best))
flags.sort()

out = []
w = out.append
w("-- BattleBallServer: seed data for the support items (V005). GENERATED by BattleBall/SourceData/tools/build_support_seed_sql.py; do not edit by hand.")
w("-- Status: PROPOSED values approved by the owner on 2026-10-07 (docs/database/BattleBall.md 10.22). Numbers come from NRO data (10.21);")
w("-- the 150-gem price, the 15-second pet interval and the training-armor points are PROPOSED defaults, all editable on the admin page.")
w("SET NAMES utf8mb4;")
w("")
w("-- Two new stat types the skill books need (NRO option 214 and 216). Enabled; the server applies them as multipliers on ultimates.")
w("INSERT INTO stat_type (stat_key, name_vi, unit, applies, enabled, suggested_max, sort_order, nro_option_ids, nro_code_ref, note, updated_by) VALUES")
w("  ('ULT_RANGE_PCT', 'Phạm vi tuyệt kỹ %', 'PCT', 'YES', 1, 10, 50, '[214]', 'NRO item option 214', 'Chỉ nhận từ sách tuyệt kỹ (PROPOSED)', 'seed'),")
w("  ('ULT_DMG_PCT', 'Sát thương tuyệt kỹ %', 'PCT', 'YES', 1, 10, 51, '[216]', 'NRO item option 216', 'Chỉ nhận từ sách tuyệt kỹ (PROPOSED)', 'seed');")
w("")
w("INSERT INTO static_data_version (domain, version, updated_by) VALUES ('SUPPORT', 1, 'seed');")
w("")
w("INSERT INTO support_kind (kind_key, name_vi, slot, updated_by) VALUES")
w("  ('PET', 'Pet', 'SUPPORT_1', 'seed'),")
w("  ('TRAIN_ARMOR', 'Giáp tập luyện', 'SUPPORT_2', 'seed'),")
w("  ('FLAG_WING_WEAPON', 'Cờ / cánh / vũ khí', 'SUPPORT_3', 'seed'),")
w("  ('SKILL_BOOK', 'Sách tuyệt kỹ', 'SUPPORT_4', 'seed');")
w("")

rows = []
for tid, stat, val, dur in PETS:
    rows.append((tid, "PET", items[tid]["NAME"], items[tid]["icon_id"], "SHOP", GEM_PRICE, "Hiệu ứng: %s +%s%% trong %ss mỗi 15s (mô tả NRO bị cắt, phần hồi kỹ năng chưa rõ)" % (stat, val, dur)))
for tid, lvl, pct in TRAIN:
    rows.append((tid, "TRAIN_ARMOR", items[tid]["NAME"], items[tid]["icon_id"], "SHOP", GEM_PRICE, "Mặc: sức đánh -%s%%; cởi ra: +%s%% theo số trận tích luỹ" % (pct, pct)))
for tid, stats in flags:
    rows.append((tid, "FLAG_WING_WEAPON", items[tid]["NAME"], items[tid]["icon_id"], "SHOP", GEM_PRICE, None))
for tid in BOOKS:
    rows.append((tid, "SKILL_BOOK", items[tid]["NAME"], items[tid]["icon_id"], "CRAFT", None, "Cách nhận chưa quyết định (OPEN); sách 1 và sách 2 khác nhau thế nào: chưa rõ, tạm dùng cùng bảng chỉ số"))

w("INSERT INTO support_item_template (support_id, kind_key, name_vi, icon_id, obtain, gem_price, note, updated_by) VALUES")
w(",\n".join("  (%s, %s, %s, %s, %s, %s, %s, 'seed')" % (r[0], q(r[1]), q(r[2]), q(r[3]), q(r[4]), q(r[5]), q(r[6])) for r in rows) + ";")
w("")
w("INSERT INTO support_pet_effect (support_id, stat_key, `value`, interval_s, duration_s, updated_by) VALUES")
w(",\n".join("  (%s, %s, %s, 15, %s, 'seed')" % (t, q(s), v, d) for t, s, v, d in PETS) + ";")
w("")
w("INSERT INTO support_train_armor (support_id, level, atk_penalty_pct, atk_bonus_pct, points_per_match, max_points, updated_by) VALUES")
w(",\n".join("  (%s, %s, %s, %s, 1, 50, 'seed')" % (t, l, p, p) for t, l, p in TRAIN) + ";")
w("")
w("INSERT INTO support_item_stat (support_id, stat_key, `value`, updated_by) VALUES")
lines = []
for tid, stats in flags:
    for k, v in sorted(stats.items()):
        lines.append("  (%s, %s, %s, 'seed')" % (tid, q(k), v))
w(",\n".join(lines) + ";")
w("")
w("INSERT INTO skill_book_template (support_id, lines_count, updated_by) VALUES")
w(",\n".join("  (%s, 1, 'seed')" % t for t in BOOKS) + ";")
w("")
w("INSERT INTO skill_book_pool (stat_key, min_value, max_value, weight, updated_by) VALUES")
w(",\n".join("  (%s, %s, %s, 1, 'seed')" % (q(k), a, b) for k, a, b in POOL) + ";")
w("")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", OUT, "pets", len(PETS), "train", len(TRAIN), "flags", len(flags), "books", len(BOOKS), "pool", len(POOL))
