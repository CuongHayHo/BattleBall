"""Generates BattleBallServer/db/migrations/V009__dungeons.sql: boss groups, boss templates, dungeons and their boss lists.

Inputs: tables/seed/boss_groups.json (from build_boss_picker.py: boss code of NRO, read-only)
        tables/seed/dungeon_choice_2026-10-07.json (the owner's choice made on boss_group_picker.html)
Boss stats of BattleBall are NOT here: HP/ATK/armor come from GDD section 7 by tier and role (OPEN); only the NRO values are kept for reference.
Safe to re-run; overwrites V009 only.
"""
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
OUT = os.path.normpath(os.path.join(SRC, "..", "..", "BattleBallServer", "db", "migrations", "V009__dungeons.sql"))
RACE = {"Trái Đất": "EARTH", "Namếc": "NAMEC", "Xayda": "XAYDA"}


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


groups = json.load(open(os.path.join(SRC, "tables", "seed", "boss_groups.json"), encoding="utf-8"))["groups"]
choice = json.load(open(os.path.join(SRC, "tables", "seed", "dungeon_choice_2026-10-07.json"), encoding="utf-8"))["dungeons"]

out = []
w = out.append
w("-- BattleBallServer: boss groups, boss templates, dungeons. GENERATED by BattleBall/SourceData/tools/build_dungeon_seed_sql.py.")
w("-- Status: PROPOSED structure; the dungeon -> boss group choice is CONFIRMED (owner, 2026-10-07, boss_group_picker.html).")
w("-- Boss names, outfits and NRO hp/dame come from the NRO boss code (read-only reference). BattleBall boss stats are NOT stored here (OPEN):")
w("-- they follow GDD section 7 by dungeon tier and boss role. All roles are NORMAL because the owner did not mark mini/final bosses yet.")
w("SET NAMES utf8mb4;")
w("SET FOREIGN_KEY_CHECKS = 0;")
w("")
w("CREATE TABLE IF NOT EXISTS boss_group (")
w("  group_key  VARCHAR(40)  NOT NULL,                  -- folder name of the NRO boss code, or a BattleBall group (hoa_khi_xayda)")
w("  label_vi   VARCHAR(120) NOT NULL,")
w("  tag        ENUM('DUNGEON','BOSS','MOB','SPECIAL','EVENT') NOT NULL,   -- MOB = small mobs that swarm during fights")
w("  enabled    TINYINT(1)   NOT NULL DEFAULT 1,")
w("  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,")
w("  updated_by VARCHAR(64)  NULL,")
w("  PRIMARY KEY (group_key)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
w("CREATE TABLE IF NOT EXISTS boss_template (")
w("  boss_id    INT UNSIGNED NOT NULL,")
w("  group_key  VARCHAR(40)  NOT NULL,")
w("  name_vi    VARCHAR(120) NOT NULL,")
w("  race       ENUM('EARTH','NAMEC','XAYDA') NULL,")
w("  part_head  INT NOT NULL,                           -- client part ids (head, body, leg), -1 = none; drawn like a skin")
w("  part_body  INT NOT NULL,")
w("  part_leg   INT NOT NULL,")
w("  nro_hp     BIGINT UNSIGNED NULL,                   -- reference only (NRO values)")
w("  nro_dame   INT UNSIGNED NULL,")
w("  enabled    TINYINT(1)   NOT NULL DEFAULT 1,")
w("  note       VARCHAR(255) NULL,")
w("  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,")
w("  updated_by VARCHAR(64)  NULL,")
w("  PRIMARY KEY (boss_id),")
w("  KEY idx_boss_group (group_key),")
w("  CONSTRAINT fk_boss_group FOREIGN KEY (group_key) REFERENCES boss_group (group_key)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
w("CREATE TABLE IF NOT EXISTS dungeon_template (")
w("  dungeon_id INT UNSIGNED NOT NULL,")
w("  name_vi    VARCHAR(120) NOT NULL,")
w("  tier       ENUM('early','mid','late') NOT NULL,    -- GDD section 7 zone tier: early / mid / late")
w("  group_key  VARCHAR(40)  NULL,                      -- one boss group per dungeon, each group used by at most one dungeon")
w("  enabled    TINYINT(1)   NOT NULL DEFAULT 1,")
w("  note       VARCHAR(255) NULL,")
w("  sort_order SMALLINT     NOT NULL DEFAULT 0,")
w("  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,")
w("  updated_by VARCHAR(64)  NULL,")
w("  PRIMARY KEY (dungeon_id),")
w("  UNIQUE KEY uq_dungeon_group (group_key),")
w("  CONSTRAINT fk_dungeon_group FOREIGN KEY (group_key) REFERENCES boss_group (group_key)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
w("CREATE TABLE IF NOT EXISTS dungeon_boss (")
w("  dungeon_id INT UNSIGNED NOT NULL,")
w("  boss_id    INT UNSIGNED NOT NULL,")
w("  role       ENUM('NORMAL','MINI','FINAL','MINION') NOT NULL DEFAULT 'NORMAL',  -- mini-boss of a floor / final boss / small mob that spawns en masse")
w("  sort_order SMALLINT     NOT NULL DEFAULT 0,")
w("  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,")
w("  updated_by VARCHAR(64)  NULL,")
w("  PRIMARY KEY (dungeon_id, boss_id),")
w("  CONSTRAINT fk_dboss_dungeon FOREIGN KEY (dungeon_id) REFERENCES dungeon_template (dungeon_id) ON DELETE CASCADE,")
w("  CONSTRAINT fk_dboss_boss    FOREIGN KEY (boss_id)    REFERENCES boss_template (boss_id)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
w("SET FOREIGN_KEY_CHECKS = 1;")
w("")
w("INSERT INTO static_data_version (domain, version, updated_by) VALUES ('DUNGEON', 1, 'seed');")
w("")

w("INSERT INTO boss_group (group_key, label_vi, tag, updated_by) VALUES")
w(",\n".join("  (%s, %s, %s, 'seed')" % (q(g["key"]), q(g["label"]), q(g["tag"])) for g in groups) + ";")
w("")

rows = []
is_minion = {}
first_id = {}
bid = 1
for g in groups:
    first_id[g["key"]] = []
    for b in g["bosses"]:
        rows.append("  (%d, %s, %s, %s, %d, %d, %d, %s, %s, 'seed')" % (
            bid, q(g["key"]), q(b["name"]), q(RACE.get(b["race"])), b["head"], b["body"], b["leg"], q(b["nroHp"]), q(b["nroDame"])))
        first_id[g["key"]].append(bid)
        is_minion[bid] = b["name"].startswith("Xên con") or g["tag"] == "MOB"
        bid += 1
w("INSERT INTO boss_template (boss_id, group_key, name_vi, race, part_head, part_body, part_leg, nro_hp, nro_dame, updated_by) VALUES")
w(",\n".join(rows) + ";")
w("")

w("INSERT INTO dungeon_template (dungeon_id, name_vi, tier, group_key, sort_order, note, updated_by) VALUES")
dl = []
for i, d in enumerate(choice, 1):
    note = None if d["group"] else "Chưa chọn nhóm boss (OPEN)"
    dl.append("  (%d, %s, %s, %s, %d, %s, 'seed')" % (i, q(d["dungeon"]), q(d["tier"]), q(d["group"]), i, q(note)))
w(",\n".join(dl) + ";")
w("")

links = []
for i, d in enumerate(choice, 1):
    if not d["group"]:
        continue
    for n, b in enumerate(first_id[d["group"]]):
        links.append("  (%d, %d, '%s', %d, 'seed')" % (i, b, "MINION" if is_minion[b] else "NORMAL", n))
w("INSERT INTO dungeon_boss (dungeon_id, boss_id, role, sort_order, updated_by) VALUES")
w(",\n".join(links) + ";")
w("")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", OUT, "| groups", len(groups), "| bosses", bid - 1, "| dungeons", len(choice), "| dungeon_boss", len(links))
