"""Generates BattleBallServer/db/migrations/V014__monster_stats.sql: HP / ATK / armor of every kind of monster by class and dungeon tier.

Numbers come from GDD section 7 (docs/gameplay/game-design-doc.md) through the constants of balance_model.py:
  HP = time-to-kill x expected team ATK fraction of the tier x Team_DPS_Max x (1 - target damage reduction)
ATK and armor ranges are the GDD table values. For mini-boss and final boss the GDD gives one row (reference tier mid / late), so their ATK keeps the
GDD ratio to the ordinary boss of the same tier (PROPOSED: otherwise an early-game final boss would hit like an endgame one).
Safe to re-run; overwrites V014 only.
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import balance_model as bm   # noqa: E402  (constants only; its main() runs under __main__)

OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "BattleBallServer", "db", "migrations", "V014__monster_stats.sql"))
TEAM_DPS = bm.MAX_ATK_TOTAL * bm.TEAM_DPS_PER_ATK
TIERS = ("early", "mid", "late")
# class -> (ttk key, armor key by tier or single, ATK % range by tier or single, armor % range by tier or single, reference tier for scaling or None)
CLASSES = {
    "MOB":   dict(ttk="mob", armor=0.075, atk=(3, 5), arm=(5, 10), ref=None),
    "ELITE": dict(ttk="elite", armor=0.175, atk=(8, 10), arm=(15, 20), ref=None),
    "BOSS":  dict(ttk={"early": "boss_early", "mid": "boss_mid", "late": "boss_late"},
                  armor={"early": 0.225, "mid": 0.34, "late": 0.44},
                  atk={"early": (20, 28), "mid": (35, 45), "late": (50, 65)}, arm={"early": (20, 25), "mid": (30, 38), "late": (40, 48)}, ref=None),
    "MINI":  dict(ttk="miniboss", armor=0.325, atk=(30, 40), arm=(30, 35), ref="mid"),
    "FINAL": dict(ttk="dungeon_final", armor=0.485, atk=(55, 70), arm=(45, 52), ref="late"),
}
GAP = {"early": 1.3, "mid": 1.8, "late": 2.2}   # GDD 7.5 global action gap by tier; mobs have none


def pick(v, tier):
    return v[tier] if isinstance(v, dict) else v


rows = []
for cls, c in CLASSES.items():
    for tier in TIERS:
        ttk = bm.TTK[pick(c["ttk"], tier)]
        armor = pick(c["armor"], tier)
        hp = round(ttk * bm.ATK_FRACTION[tier] * TEAM_DPS * (1 - armor))
        lo, hi = pick(c["atk"], tier)
        if c["ref"]:
            # same ratio to the ordinary boss of the tier as in the GDD table at the reference tier (mini-boss vs boss mid, final vs boss late)
            blo, bhi = CLASSES["BOSS"]["atk"][tier]
            rlo, rhi = CLASSES["BOSS"]["atk"][c["ref"]]
            lo, hi = round(blo * c["atk"][0] / rlo, 2), round(bhi * c["atk"][1] / rhi, 2)
        alo, ahi = pick(c["arm"], tier)
        gap = GAP[tier] if cls in ("BOSS", "MINI", "FINAL") else None
        rows.append((cls, tier, ttk, hp, lo, hi, alo, ahi, gap))

out = []
w = out.append
w("-- BattleBallServer: monster stats by class and dungeon tier. GENERATED by BattleBall/SourceData/tools/build_monster_stats_sql.py.")
w("-- Status: PROPOSED, from GDD section 7 (HP from the time-to-kill formula; ATK % of Max_ATK_Total; armor = damage reduction %). Edit on the admin page.")
w("-- Depends on V009 to V012 (dungeon_boss, boss_template). Per-boss tuning: boss_template.hp_mult and atk_mult (default 1).")
w("SET NAMES utf8mb4;")
w("")
w("CREATE TABLE IF NOT EXISTS monster_stat_class (")
w("  class_key     ENUM('MOB','ELITE','BOSS','MINI','FINAL') NOT NULL,")
w("  tier          ENUM('early','mid','late') NOT NULL,")
w("  ttk_seconds   DECIMAL(6,1)  NOT NULL,                 -- design time for the expected team to kill it")
w("  hp            BIGINT UNSIGNED NOT NULL,")
w("  atk_pct_min   DECIMAL(6,2)  NOT NULL,                 -- % of Max_ATK_Total per hit (random inside the range)")
w("  atk_pct_max   DECIMAL(6,2)  NOT NULL,")
w("  armor_pct_min DECIMAL(5,2)  NOT NULL,                 -- damage reduction of the monster, %")
w("  armor_pct_max DECIMAL(5,2)  NOT NULL,")
w("  action_gap_s  DECIMAL(4,1)  NULL,                     -- seconds between boss actions (GDD 7.5); NULL for small mobs")
w("  note          VARCHAR(255)  NULL,")
w("  updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,")
w("  updated_by    VARCHAR(64)   NULL,")
w("  PRIMARY KEY (class_key, tier)")
w(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;")
w("")
for col in ("hp_mult", "atk_mult"):
    w("SET @has_col = (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'boss_template' AND COLUMN_NAME = '%s');" % col)
    w("SET @ddl = IF(@has_col = 0, 'ALTER TABLE boss_template ADD COLUMN %s DECIMAL(5,2) NOT NULL DEFAULT 1.00', 'SELECT 1');" % col)
    w("PREPARE stmt FROM @ddl; EXECUTE stmt; DEALLOCATE PREPARE stmt;")
w("")
w("INSERT INTO monster_stat_class (class_key, tier, ttk_seconds, hp, atk_pct_min, atk_pct_max, armor_pct_min, armor_pct_max, action_gap_s, note, updated_by) VALUES")
note = {"MINI": "ATK giữ đúng tỉ lệ GDD so với boss thường cùng cấp vùng (khớp bảng GDD ở vùng giữa)", "FINAL": "ATK giữ đúng tỉ lệ GDD so với boss thường cùng cấp vùng (khớp bảng GDD ở vùng cuối)"}
vals = []
for cls, tier, ttk, hp, lo, hi, alo, ahi, gap in rows:
    n = note.get(cls)
    vals.append("  ('%s', '%s', %s, %d, %s, %s, %s, %s, %s, %s, 'seed')" % (
        cls, tier, ttk, hp, lo, hi, alo, ahi, "NULL" if gap is None else gap, "NULL" if n is None else "'" + n + "'"))
w(",\n".join(vals) + ";")
w("")
w("-- What every dungeon fight contains, with the final numbers (class from the role, tier from the dungeon).")
w("CREATE OR REPLACE VIEW v_dungeon_monster AS")
w("SELECT d.dungeon_id, d.name_vi AS dungeon, d.tier, b.boss_id, b.name_vi AS boss, x.role,")
w("  (CASE x.role WHEN 'NORMAL' THEN 'BOSS' WHEN 'MINI' THEN 'MINI' WHEN 'FINAL' THEN 'FINAL' ELSE COALESCE(x.mob_tier, 'MOB') END) AS class_key,")
w("  ROUND(s.hp * b.hp_mult) AS hp,")
w("  ROUND((s.atk_pct_min + s.atk_pct_max) / 200 * b.atk_mult * (SELECT CAST(value_json AS UNSIGNED) FROM balance_config WHERE config_key = 'max_atk_total')) AS atk_per_hit,")
w("  (s.armor_pct_min + s.armor_pct_max) / 2 AS armor_reduction_pct,")
w("  s.action_gap_s")
w("FROM dungeon_boss x")
w("JOIN dungeon_template d ON d.dungeon_id = x.dungeon_id")
w("JOIN boss_template b ON b.boss_id = x.boss_id")
w("JOIN monster_stat_class s ON s.tier = d.tier AND s.class_key = (CASE x.role WHEN 'NORMAL' THEN 'BOSS' WHEN 'MINI' THEN 'MINI' WHEN 'FINAL' THEN 'FINAL' ELSE COALESCE(x.mob_tier, 'MOB') END);")
w("")
w("INSERT INTO static_data_version (domain, version, updated_by) VALUES ('MONSTER', 1, 'seed')")
w("  ON DUPLICATE KEY UPDATE version = version + 1, updated_by = 'seed';")
w("")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", OUT, "| Team_DPS_Max", round(TEAM_DPS))
for r in rows:
    print("  %-5s %-5s ttk %-5s hp %14s atk %s-%s%% armor %s-%s%% gap %s" % ((r[0], r[1], r[2], format(r[3], ",")) + r[4:]))
